def job(workflow: str, name: str) -> str:
    start = re.search(rf'^  {re.escape(name)}:\s*$', workflow, re.M)
    if start is None:
        raise ValueError(f'missing canonical job: {name}')
    rest = workflow[start.start():]
    following = re.search(r'^  [a-zA-Z_][a-zA-Z_0-9]*:\s*$', rest[start.end() - start.start():], re.M)
    if following:
        rest = rest[:start.end() - start.start() + following.start()]
    return rest.rstrip() + '\n'


def generate(workflow: str) -> str:
    go = re.search(r"^  GO_VERSION: '([0-9.]+)'", workflow, re.M)
    flutter = re.search(r"^  FLUTTER_VERSION: '([0-9.]+)'", workflow, re.M)
    installers = set(re.findall(r'uses: onesyue/yuelink-ci/\.github/actions/setup-flutter@([0-9a-f]{40})', workflow))
    if flutter is None or len(installers) != 1:
        raise ValueError('canonical workflow must have one reviewed Flutter SDK and installer')
    baseline = re.search(r'^      EXPECTED_BASELINE_REVISION: [\'\"]?([0-9a-f]{40})[\'\"]?\s*$', workflow, re.M)
    if go is None or baseline is None:
        raise ValueError('canonical workflow must pin Go and the exact baseline revision')
    dial = job(workflow, 'dial_gate')
    summary = job(workflow, 'dial_gate_summary')
    if dial.count('needs: [source_binding]') != 1 or summary.count('needs: [source_binding, dial_gate]') != 1:
        raise ValueError('canonical dial job dependencies changed')
    dial = dial.replace('needs: [source_binding]', 'needs: [dial_source_binding]')
    summary = summary.replace('needs: [source_binding, dial_gate]', 'needs: [dial_source_binding, dial_gate]')
    for name, block in (('dial', dial), ('summary', summary)):
        expression = "needs.dial_source_binding.result == 'success'"
        if name == 'summary':
            expression = "always() && needs.dial_source_binding.result == 'success' && needs.dial_gate.result != 'cancelled'"
        block, count = re.subn(r'    if: >-\n(?:      .*\n)+', f'    if: {expression}\n', block, count=1)
        if count != 1:
            raise ValueError(f'canonical {name} admission changed')
        block = block.replace('needs.source_binding.outputs.source_commit', 'needs.dial_source_binding.outputs.candidate_commit')
        block = block.replace('      actions: write', '      actions: read')
        if 'needs.source_binding' in block or 'dialgate_candidate_ref' in block:
            raise ValueError('verification job retains a release dependency or candidate override')
        if name == 'dial':
            if 'github.event.pull_request.head.sha' in block:
                raise ValueError('private candidate must not use the public builder PR head')
            dial = block
        else:
            block = block.replace("          DIAL_SOURCE_PR: ''", "          DIAL_SOURCE_PR: ${{ needs.dial_source_binding.outputs.source_pr }}")
            block = block.replace("          DIAL_VERIFICATION_ONLY: 'false'", "          DIAL_VERIFICATION_ONLY: 'true'")
            summary = block
    header = HEADER.replace('__GO_VERSION__', go[1]).replace('__FLUTTER_VERSION__', flutter[1]).replace('__BASELINE__', baseline[1]).replace('__CHECKOUT__', CHECKOUT)
    client = LINUX_CLIENT_TESTS.replace('__CHECKOUT__', CHECKOUT).replace('__FLUTTER_INSTALLER__', next(iter(installers)))
    return header + client + dial + '\n' + summary


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--build', type=Path, default=Path('.github/workflows/build.yml'))
    parser.add_argument('--output', type=Path, default=Path('.github/workflows/dialgate-verify.yml'))
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate(args.build.read_text())
    if args.check:
        if not args.output.exists() or args.output.read_text() != result:
            raise SystemExit('verification workflow differs from canonical dial jobs')
    else:
        args.output.write_text(result)


if __name__ == '__main__':
    main()
